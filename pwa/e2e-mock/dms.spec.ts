import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';
import { addVirtualAuthenticator } from '../e2e/virtual-authenticator';
import { MOCK_SETUP_TOKEN } from '../mock/api';
import { MOCK_MAX_UPLOAD_BYTES, MOCK_QUARANTINE_MARKER } from '../mock/dms';

// WP-F4 against the mock backend. All files are synthetic. The mock completes "processing" after ~0.7 s and exposes
// the ingest state as a mock-only extension (see mock/dms.ts); the real backend has no such route yet.

test.beforeEach(async ({ request }) => {
	expect((await request.post('/api/__mock/reset')).status()).toBe(204);
});

async function bootstrap(page: Page, context: Parameters<typeof addVirtualAuthenticator>[0]) {
	await addVirtualAuthenticator(context, page);
	await page.goto('/setup');
	await page.getByLabel('Setup-Token').fill(MOCK_SETUP_TOKEN);
	await page.getByLabel('Kennung').fill('root');
	await page.getByLabel('Anzeigename').fill('Root');
	await page.getByRole('button', { name: 'Passkey anlegen und starten' }).click();
	await expect(page).toHaveURL(/\/dashboard$/);
	await page.goto('/settings/modules');
	await page.getByTestId('module-toggle-dms').click();
	await expect(page.getByTestId('nav-dms')).toBeVisible();
	await page.getByTestId('nav-dms').click();
	await expect(page.getByTestId('dms-search')).toBeVisible();
}

const pdf = (text: string) => ({ name: 'beleg.pdf', mimeType: 'application/pdf', buffer: Buffer.from(`%PDF-1.4\n% ${text}\n%%EOF\n`) });
// 1x1 transparent PNG, generated bytes (no real data).
const PNG_1X1 = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGNgYGBgAAAABQABh6FO1AAAAABJRU5ErkJggg==', 'base64');

async function upload(page: Page, ...files: { name: string; mimeType: string; buffer: Buffer }[]) {
	await page.getByTestId('dms-file-input').setInputFiles(files);
}

async function expectNoSeriousA11y(page: Page) {
	const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
	const bad = result.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical');
	expect(bad.map((v) => `${v.id}: ${v.nodes.map((n) => n.target.join(' ')).join(' | ')}`)).toEqual([]);
}

test('AK-F4-1 upload -> processing finished -> hit in search with highlighted snippet (never as HTML)', async ({ page, context }) => {
	await bootstrap(page, context);
	await upload(page, pdf('Quartalsabrechnung <script>window.__xss=1</script> Zeitschrift'));
	const item = page.getByTestId('dms-upload-item');
	await expect(item).toHaveAttribute('data-state', 'processing');
	await expect(item).toHaveAttribute('data-state', 'done', { timeout: 10_000 });

	// Text is not searchable before processing is done in the mock, so this hit proves the "done" state is real.
	await page.getByTestId('dms-search').fill('Quartalsabrechnung');
	await page.getByTestId('dms-search-submit').click();
	await expect(page).toHaveURL(/q=Quartalsabrechnung/);
	const snippet = page.getByTestId('dms-snippet').first();
	await expect(snippet.locator('mark')).toHaveText('Quartalsabrechnung');
	await expect(snippet).toContainText('<script>window.__xss=1</script>');
	await expect(snippet.locator('script')).toHaveCount(0);
	expect(await page.evaluate(() => (window as unknown as { __xss?: number }).__xss)).toBeUndefined();
	await expect(page.getByTestId('dms-count')).toContainText('1 Treffer');
	await expectNoSeriousA11y(page);

	await page.getByTestId('dms-search').fill('gibtesnicht');
	await page.getByTestId('dms-search-submit').click();
	await expect(page.getByTestId('dms-empty')).toContainText('Keine Treffer');
});

test('AK-F4-4 error states: unsupported type, too large, duplicate, quarantine are visible', async ({ page, context }) => {
	await bootstrap(page, context);
	await upload(page, { name: 'notiz.txt', mimeType: 'text/plain', buffer: Buffer.from('keine erlaubte Datei') });
	const unsupported = page.locator('[data-testid=dms-upload-item]').filter({ hasText: 'notiz.txt' });
	await expect(unsupported.getByTestId('dms-upload-error')).toHaveAttribute('data-failure', 'unsupported');
	await expect(unsupported).toContainText('nicht unterstützt');

	await upload(page, {
		name: 'riesig.pdf',
		mimeType: 'application/pdf',
		buffer: Buffer.concat([Buffer.from('%PDF-1.4\n'), Buffer.alloc(MOCK_MAX_UPLOAD_BYTES + 10)])
	});
	const big = page.locator('[data-testid=dms-upload-item]').filter({ hasText: 'riesig.pdf' });
	await expect(big.getByTestId('dms-upload-error')).toHaveAttribute('data-failure', 'too_large');
	await expect(big).toContainText('zu groß');

	await upload(page, pdf('Duplikat Inhalt'));
	await expect(page.getByTestId('dms-upload-done')).toBeVisible({ timeout: 10_000 });
	await upload(page, pdf('Duplikat Inhalt'));
	await expect(page.getByTestId('dms-upload-duplicate')).toContainText('Duplikat');
	await expect(page.getByTestId('dms-upload-duplicate').getByRole('link')).toHaveAttribute('href', /\/dms\/[0-9a-f-]{36}$/);

	await upload(page, pdf(`${MOCK_QUARANTINE_MARKER} kaputt`));
	await expect(page.getByTestId('dms-upload-quarantine')).toContainText('Quarantäne');
	await expect(page.getByTestId('dms-row-quarantine')).toBeVisible();
	await expectNoSeriousA11y(page);

	// Quarantine is also shown in the detail view.
	await page.getByTestId('dms-row').filter({ has: page.getByTestId('dms-row-quarantine') }).getByRole('link').first().click();
	await expect(page.getByTestId('dms-quarantine-banner')).toContainText('dauerhaft fehlgeschlagen');
});

