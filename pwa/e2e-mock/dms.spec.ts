test('detail: PDF is previewed in a frame from a blob URL, filters and facets narrow the search', async ({ page, context }) => {
	await bootstrap(page, context);
	await upload(page, { ...pdf('Mietvertrag Wohnung'), name: 'miete.pdf' });
	await expect(page.getByTestId('dms-upload-done')).toBeVisible({ timeout: 10_000 });
	await upload(page, { ...pdf('Mietnebenkosten Heizung'), name: 'neben.pdf' });
	await expect(page.getByTestId('dms-upload-done')).toHaveCount(2, { timeout: 10_000 });

	// Classify one document so type facets exist.
	await page.getByTestId('dms-row').filter({ hasText: 'miete' }).getByRole('link').first().click();
	await expect(page.getByTestId('dms-preview-pdf')).toHaveAttribute('src', /^blob:/);
	await page.getByTestId('dms-edit-type').selectOption({ label: 'Vertrag' });
	await page.getByTestId('dms-edit-date').fill('2025-06-01');
	await page.getByTestId('dms-save').click();
	await expect(page.getByTestId('dms-saved')).toBeVisible();
	await page.getByTestId('dms-back').click();

	await page.getByTestId('dms-search').fill('Miet');
	await page.getByTestId('dms-search-submit').click();
	await expect(page.getByTestId('dms-row')).toHaveCount(2);
	await expect(page.getByTestId('dms-facets')).toBeVisible();
	await page.getByTestId('dms-facet-document_type').filter({ hasText: 'Vertrag' }).click();
	await expect(page.getByTestId('dms-row')).toHaveCount(1);
	await expect(page).toHaveURL(/type=/);
	await page.getByTestId('dms-facet-year').filter({ hasText: '2025' }).click();
	await expect(page).toHaveURL(/from=2025-01-01/);
	await expect(page.getByTestId('dms-row')).toHaveCount(1);
	await page.getByTestId('dms-facet-year').filter({ hasText: '2025' }).click();
	await page.getByTestId('dms-filter-to').fill('2024-12-31');
	await expect(page.getByTestId('dms-empty')).toBeVisible();
	// Filters live in the URL: a reload keeps them.
	await page.reload();
	await expect(page.getByTestId('dms-empty')).toBeVisible();
});

test('trash: reason is required, trashed documents leave the list and can be restored', async ({ page, context }) => {
	await bootstrap(page, context);
	await upload(page, pdf('Altlast Dokument'));
	await expect(page.getByTestId('dms-upload-done')).toBeVisible({ timeout: 10_000 });
	await page.getByTestId('dms-row').first().getByRole('link').first().click();

	await page.getByTestId('dms-trash').click();
	await expect(page.getByTestId('error-banner')).toContainText('Grund');
	await page.getByTestId('dms-trash-reason').fill('Doppelt erfasst');
	await page.getByTestId('dms-trash').click();
	await expect(page.getByTestId('dms-trashed-banner')).toContainText('Doppelt erfasst');
	await expect(page.getByTestId('dms-save')).toBeDisabled();

	await page.getByTestId('dms-back').click();
	await expect(page.getByTestId('dms-empty')).toBeVisible();
	await page.getByTestId('dms-filters').locator('summary').click();
	await page.getByTestId('dms-trash-toggle').check();
	await expect(page.getByTestId('dms-row')).toHaveCount(1);
	await expectNoSeriousA11y(page);
	await page.getByTestId('dms-row').first().getByRole('link').first().click();
	await page.getByTestId('dms-restore').click();
	await expect(page.getByTestId('dms-trashed-banner')).toHaveCount(0);
	await expect(page.getByTestId('dms-save')).toBeEnabled();
});

test('AK-F4-3 keyboard: one tab stop, arrows/J/K/Home/End, Enter opens, "/" focuses the search, paging', async ({ page, context, request }) => {
	await bootstrap(page, context);
	expect((await request.post('/api/__mock/dms/seed', { data: { count: 30 } })).status()).toBe(204);
	await page.reload();
	await expect(page.getByTestId('dms-row')).toHaveCount(25);
	await expect(page.getByTestId('dms-count')).toContainText('25 Dokumente');

	const links = page.locator('a[data-row-link]');
	await expect(page.locator('a[data-row-link][tabindex="0"]')).toHaveCount(1);
	await links.first().focus();
	await page.keyboard.press('ArrowDown');
	await page.keyboard.press('ArrowDown');
	await expect(links.nth(2)).toBeFocused();
	await page.keyboard.press('k');
	await expect(links.nth(1)).toBeFocused();
	await page.keyboard.press('j');
	await expect(links.nth(2)).toBeFocused();
	await page.keyboard.press('End');
	await expect(links.last()).toBeFocused();
	await page.keyboard.press('Home');
	await expect(links.first()).toBeFocused();
	await expect(page.locator('a[data-row-link][tabindex="0"]')).toHaveCount(1);

	await page.keyboard.press('/');
	await expect(page.getByTestId('dms-search')).toBeFocused();
	await page.keyboard.press('Tab');
	await page.keyboard.press('Tab');

	// Cursor pagination
	await page.getByTestId('dms-more').click();
	await expect(page.getByTestId('dms-row')).toHaveCount(30);
	await expect(page.getByTestId('dms-more')).toHaveCount(0);

	await links.nth(3).focus();
	await page.keyboard.press('Enter');
	await expect(page).toHaveURL(/\/dms\/[0-9a-f-]{36}$/);
	await expect(page.getByTestId('dms-detail-title')).toContainText('Seed');
});

test('a reader without download right sees metadata but no original and no preview', async ({ page, context, browser }) => {
	await bootstrap(page, context);
	await upload(page, pdf('Vertraulich Bericht'));
	await expect(page.getByTestId('dms-upload-done')).toBeVisible({ timeout: 10_000 });

	await page.goto('/settings/members');
	await page.locator('#invite-role').selectOption('customer_viewer');
	await page.getByTestId('invite-create').click();
	const link = (await page.getByTestId('invite-link').innerText()).trim();
	const path = link.startsWith('http') ? new URL(link).pathname : link;

	const viewerContext = await browser.newContext({ baseURL: page.url().split('/settings')[0], locale: 'de-DE' });
	const viewer = await viewerContext.newPage();
	await addVirtualAuthenticator(viewerContext, viewer);
	await viewer.goto(path);
	await viewer.getByLabel('Kennung').fill('lesen');
	await viewer.getByLabel('Anzeigename').fill('Leser');
	await viewer.getByRole('button', { name: 'Passkey anlegen' }).click();
	await expect(viewer).toHaveURL(/\/dashboard$/);
	await viewer.getByTestId('nav-dms').click();
	await viewer.getByTestId('dms-row').first().getByRole('link').first().click();
	await expect(viewer.getByTestId('dms-detail-title')).toBeVisible();
	await expect(viewer.getByTestId('dms-download')).toHaveCount(0);
	await expect(viewer.getByTestId('dms-no-download')).toBeVisible();
	await expect(viewer.getByTestId('dms-preview-none')).toBeVisible();
	await expect(viewer.getByTestId('dms-save')).toBeDisabled();
	await expect(viewer.getByTestId('dms-trash')).toHaveCount(0);
	// No upload panel either (no create right).
	await viewer.getByTestId('dms-back').click();
	await expect(viewer.getByTestId('dms-upload')).toHaveCount(0);
	await viewerContext.close();
});
